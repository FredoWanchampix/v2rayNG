package com.v2ray.ang.service

/**
 * Политика СКОУПА действий на финише теста профилей.
 *
 * Инвариант (первопричина трёх дефектов, найденных по вещдокам кода и лога
 * владельца 22.11.2026): **скоуп действия на финише обязан совпадать со скоупом
 * ИЗМЕРЕНИЯ**. Воркер выбирает, что мерить, так:
 * ```
 * val guidsList = when {
 *     message.serverGuids.isNotEmpty()   -> message.serverGuids          // фильтр по ключевому слову
 *     message.subscriptionId.isNotEmpty() -> decodeServerList(subscriptionId) // одна подписка
 *     else                                -> decodeAllServerList()        // вкладка «Все»
 * }
 * ```
 * а действия на финише (авто-удаление недействительных, авто-сортировка) раньше
 * были завязаны ТОЛЬКО на `subscriptionId.isNotEmpty()`. Отсюда:
 *
 * 1. вкладка «Все» (`subscriptionId == ""`) — ни удаление, ни сортировка по пингу
 *    не выполнялись ВОВСЕ, хотя воркер измерил каждый профиль каждой подписки;
 * 2. при активном фильтре (`serverGuids` непуст) измерены только отфильтрованные
 *    профили, а удаление шло по ВСЕЙ подписке — то есть стирались профили,
 *    которые в этом прогоне не мерились вовсе (потеря данных);
 * 3. сортировка по скорости после «Поиска стабильных профилей» имела те же две
 *    дыры (закрыты отдельно: она ещё и обязана быть безусловной).
 *
 * Обе функции — ЧИСТЫЕ (только данные, без MMKV/Android), поэтому доказываются
 * JVM-тестом TestFinishScopePolicyTest.
 */
object TestFinishScopePolicy {

    /**
     * Скоуп авто-удаления недействительных профилей на финише.
     *
     * Значение NONE не вводится намеренно: «ничего не делать» означало бы
     * вернуть дефект №1. Пустой `serverGuids` + пустой `subscriptionId` — это
     * вкладка «Все», то есть [ALL].
     */
    enum class InvalidCleanup {
        /** Удалить только явно измеренные профили (активен фильтр по слову). */
        GUIDS,

        /** Удалить недействительные внутри одной подписки (прежнее поведение). */
        SUBSCRIPTION,

        /** Удалить недействительные во всех подписках, как делает меню на вкладке «Все». */
        ALL,
    }

    /**
     * Скоуп авто-удаления недействительных профилей.
     *
     * Порядок веток важен: `serverGuids` проверяется ПЕРВЫМ, потому что он
     * непуст только при активном фильтре, а при фильтре `subscriptionId` тоже
     * может быть непуст — и тогда удаление по всей подписке стёрло бы
     * неизмеренные профили (дефект №2).
     *
     * @param serverGuids guid'ы, которые воркер фактически измерил; пусты, если
     *   фильтра по ключевому слову не было.
     * @param subscriptionId подписка, по которой запущен тест; пуста на «Все».
     */
    fun invalidCleanup(serverGuids: List<String>, subscriptionId: String): InvalidCleanup = when {
        serverGuids.isNotEmpty() -> InvalidCleanup.GUIDS
        subscriptionId.isNotEmpty() -> InvalidCleanup.SUBSCRIPTION
        else -> InvalidCleanup.ALL
    }

    /**
     * Какие списки серверов сортировать на финише теста.
     *
     * Одинаково для обоих видов сортировки (по пингу после обычного теста и по
     * скорости после «Поиска стабильных профилей»): отличается только вызываемая
     * функция сортировки, а не скоуп.
     *
     * - [subscriptionId] не пуст — тест шёл по одной подписке, сортируем её;
     * - пуст (вкладка «Все») — тест шёл по `decodeAllServerList`, то есть по
     *   каждой подписке плюс непрогруппированным серверам. Порядок серверов
     *   хранится ОТДЕЛЬНО для каждой подписки (`SUB_SERVERS_<id>`), поэтому
     *   сортируются все списки по очереди — ровно так, как это делают пункты меню
     *   «Сортировка по задержке» / «Сортировка по скорости»
     *   (`MainViewModel.sortByTestResultsInternal` / `sortBySpeedResultsAsync`:
     *   `subs.forEach { … }`).
     *
     * [defaultSubId] добавляется первым, когда его нет в [subsList]:
     * `MmkvManager.decodeSubsList` может его не содержать, а непрогруппированные
     * серверы воркер тоже измерил (повтор логики `decodeAllServerList`).
     *
     * ОСОЗНАННОЕ ОТЛИЧИЕ от [invalidCleanup]: скоуп сортировки НЕ сужается до
     * `serverGuids` при активном фильтре. Сортировка не разрушает данные (порядок
     * меняется по уже сохранённым измерениям), и это ровно поведение пунктов меню
     * «Сортировка по задержке»/«по скорости» — они сортируют список подписки
     * целиком, а не только видимую выборку. Сужать скоуп здесь означало бы
     * разойтись с эталоном, на который указал владелец. Инвариант «скоуп действия
     * = скоуп измерения» применяется только к ДЕСТРУКТИВНОМУ удалению, где ошибка
     * стоит пользователю профилей.
     *
     * @param subscriptionId подписка, по которой шёл тест; пуста — «Все».
     * @param subsList известные подписки из индекса.
     * @param defaultSubId идентификатор подписки непрогруппированных серверов.
     * @return идентификаторы списков, которые нужно отсортировать.
     */
    fun sortTargets(
        subscriptionId: String,
        subsList: List<String>,
        defaultSubId: String,
    ): List<String> {
        if (subscriptionId.isNotEmpty()) return listOf(subscriptionId)
        val targets = ArrayList<String>(subsList.size + 1)
        if (!subsList.contains(defaultSubId)) targets.add(defaultSubId)
        targets.addAll(subsList)
        return targets
    }
}
