package com.v2ray.ang.service

/**
 * Политика итоговой сортировки после «Поиска стабильных профилей».
 *
 * Требование владельца (22.11.2026): «когда именно функция поиск стабильных
 * профилей закончит работать, чтобы она сортировала не по пингу, а по скорости».
 *
 * Поиск заканчивается фазой СКОРОСТИ, поэтому итоговый порядок обязан быть по
 * скорости, а не по пингу, и это требование БЕЗУСЛОВНО: свитч
 * `PREF_AUTO_SORT_AFTER_TEST` описывает прежнее поведение обычного теста
 * задержки (сортировка по пингу) и не должен гасить сортировку по скорости
 * после поиска.
 *
 * Чистая функция — доказывается JVM-тестом WhitelistSortTargetsTest.
 */
object WhitelistSortPolicy {

    /**
     * Какие списки серверов сортировать на финише поиска.
     *
     * У финиша поиска ДВЕ поверхности, и обе обязаны сортироваться:
     * 1. выбрана конкретная подписка ([subscriptionId] не пуст) — воркер мерил её
     *    серверы, сортируем этот единственный список;
     * 2. вкладка «Все» ([subscriptionId] пуст) — воркер мерил
     *    `MmkvManager.decodeAllServerList`, то есть КАЖДУЮ подписку плюс
     *    непрогруппированные серверы. Порядок серверов хранится отдельно для
     *    каждой подписки, поэтому сортируются все списки по очереди — ровно так
     *    же, как это делает пункт меню «Сортировка по скорости»: сортировка
     *    одного объединённого списка не изменила бы порядок ни в одной подписке.
     *
     * [defaultSubId] добавляется первым, когда его нет в [subsList]:
     * `MmkvManager.decodeSubsList` может его не содержать, а непрогруппированные
     * серверы воркер тоже измерил (это повтор логики `decodeAllServerList`).
     *
     * @param subscriptionId подписка, по которой шёл поиск; пустая — «Все».
     * @param subsList известные подписки из индекса.
     * @param defaultSubId идентификатор подписки непрогруппированных серверов.
     * @return идентификаторы списков, которые нужно отсортировать по скорости.
     */
    fun targets(
        subscriptionId: String,
        subsList: List<String>,
        defaultSubId: String,
    ): List<String> {
        if (subscriptionId.isNotEmpty()) return listOf(subscriptionId)
        val targets = ArrayList<String>(subsList.size + 1)
        if (!subsList.contains(defaultSubId)) targets.add(defaultSubId)
        targets.addAll(subsList)
        return targets
    }
}
